"""Bind original PLT times and observation indices to each frozen coordinate record."""
from collections import defaultdict, deque
import argparse
import csv
import gzip
import hashlib
import json
import pickle
from pathlib import Path
import time
import warnings

import numpy as np


def coordinates_key(a):
    a=np.ascontiguousarray(a,dtype='<f8')
    return hashlib.sha256(len(a).to_bytes(8,'little')+a.tobytes()).hexdigest()

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source-dir',type=Path,required=True,help='GeoLife Data directory')
    p.add_argument('--coordinates',type=Path,required=True,help='Trusted coordinate pickle generated by prepare_geolife_beijing.py')
    p.add_argument('--out',type=Path,required=True,help='New metadata directory')
    a=p.parse_args()
    DATA=a.source_dir; SOURCE=a.coordinates; OUT=a.out
    if not DATA.is_dir():p.error('Source Data directory does not exist')
    OUT.mkdir(parents=True,exist_ok=False)
    started=time.time()
    with SOURCE.open('rb') as f:reference=pickle.load(f)
    lookup=defaultdict(deque)
    for i,coords in enumerate(reference):lookup[coordinates_key(coords)].append(i)
    times=[None]*len(reference);positions=[None]*len(reference);records=[];unbound_files=[]
    files=sorted(DATA.glob('*/Trajectory/*.plt'))
    assert files, 'Original PLT directory is missing'
    for number,path in enumerate(files):
        with warnings.catch_warnings():
            warnings.simplefilter('ignore',UserWarning)
            raw=np.loadtxt(path,delimiter=',',skiprows=6,usecols=(0,1,4),ndmin=2)
        if len(raw)<2:continue
        mask=(raw[:,0]>=39.75)&(raw[:,0]<=40.15)&(raw[:,1]>=116.10)&(raw[:,1]<=116.65)
        index=np.flatnonzero(mask)
        if len(index)<2:continue
        selected=raw[index,:2]
        key=coordinates_key(selected)
        if not lookup[key]:
            unbound_files.append(str(path));continue
        i=lookup[key].popleft()
        # Exact coordinate comparison, not a match by file name or trajectory count.
        if not np.array_equal(reference[i],selected):raise ValueError('Coordinate mismatch')
        days=raw[index,2]
        times[i]=days;positions[i]=index.astype(np.uint32)
        gaps=np.diff(days)*86400.
        records.append(dict(source_index=i,plt_file=str(path.relative_to(DATA)),points=len(index),raw_points=len(raw),
            coordinate_sha256=key,nonconsecutive_original_observation_pairs=int((np.diff(index)>1).sum()),
            time_gaps_over_300s=int((gaps>300).sum()),nonpositive_time_differences=int((gaps<=0).sum()),
            max_time_gap_s=float(gaps.max(initial=0))))
        if number%1000==0:print(f'PLT {number}/{len(files)}; bound {len(records)}/{len(reference)}',flush=True)
    with (OUT/'source_binding.csv').open('w',encoding='utf-8',newline='') as f:
        if not records:raise ValueError('No exact coordinate bindings found')
        writer=csv.DictWriter(f,fieldnames=list(records[0]));writer.writeheader();writer.writerows(sorted(records,key=lambda r:r['source_index']))
    missing=[i for i,value in enumerate(times) if value is None]
    report=dict(original_plt_files=len(files),frozen_records=len(reference),exactly_bound_records=len(records),
        unbound_record_indices=missing,unbound_eligible_files=unbound_files,
        trajectories_with_removed_original_points=sum(r['nonconsecutive_original_observation_pairs']>0 for r in records),
        trajectories_with_time_gap_over_300s=sum(r['time_gaps_over_300s']>0 for r in records),
        trajectories_with_nonpositive_time_differences=sum(r['nonpositive_time_differences']>0 for r in records),
        elapsed_seconds=time.time()-started,
        timestamp_format='Original GeoLife PLT column 4 day serial; differences * 86400 = seconds',
        status='BOUND' if not missing else 'INCOMPLETE_DO_NOT_USE_AS_SYNTHESIS_INPUT')
    (OUT/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    if not missing:
        for name,value in [('timestamps_day_serial.pkl.gz',times),('original_observation_indices.pkl.gz',positions)]:
            with gzip.open(OUT/name,'wb',compresslevel=3) as f:pickle.dump(value,f,pickle.HIGHEST_PROTOCOL)
    print(json.dumps(report,ensure_ascii=False,indent=2),flush=True)
    if missing:raise SystemExit(2)

if __name__=='__main__':main()
